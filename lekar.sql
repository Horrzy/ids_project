-- Tabulka pro pojišťovny
create table pojistovny (
   cislo_pojistovny  number(3) primary key,
   nazev             varchar2(100) not null,
   adresa            varchar2(200)
);

-- Tabulka pro pacienty (základní entita)
create table pacienti (
   cislo_pacienta    number
      generated by default as identity
   primary key,
   jmeno             varchar2(50) not null,
   prijmeni          varchar2(50) not null,
   rodne_cislo       varchar2(11) not null, -- Formát: YYMMDD/XXXX nebo YYMMDDXXXX
   telefon           varchar2(20),
   datum_narozeni    date,
   adresa            varchar2(200),
   cislo_pojistovny  number(3) not null,
   constraint chk_rodne_cislo 
      check ( regexp_like ( rodne_cislo, '^[0-9]{6}/?[0-9]{3,4}$' ) ),
   constraint fk_pacienti_pojistovny foreign key ( cislo_pojistovny )
      references pojistovny ( cislo_pojistovny )
);

-- Vysvětlení generalizace (v komentáři SQL kódu):
-- Zvolili jsme metodu "Multiple tables with linked PKs" (pro každý podtyp samostatná tabulka).
-- Tabulka 'pacienti' obsahuje společné atributy. 
-- Tabulka 'pacienti_registrovani' uchovává specifická data (číslo karty) a odkazuje na PK v 'pacienti'.
-- Akutní případy nevyžadují specifické atributy, jsou tedy reprezentovány pouze v základní tabulce.

-- Specializovaná tabulka pro registrované pacienty
create table pacienti_registrovani (
   cislo_pacienta    number primary key,
   cislo_karty       number not null unique,
   constraint fk_registrovani_pacienti foreign key ( cislo_pacienta )
      references pacienti ( cislo_pacienta )
         on delete cascade
);

-- Tabulka pro lékařské výkony (katalog)
create table vykony (
   typ_vykonu        number
      generated by default as identity
   primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500)
);

-- Tabulka pro typy očkování
create table typy_ockovani (
   typ_ockovani_id   number
      generated by default as identity
   primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500),
   doba_ucinnosti    number -- Počet měsíců
);

-- Tabulka pro pravidelné prohlídky
create table pravidelne_prohlidky (
   typ_prohlidky     number
      generated by default as identity
   primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500),
   doba_frekvence    number -- Počet měsíců
);

-- Tabulka pro léky
create table leky (
   cislo_leku        number
      generated by default as identity
   primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500)
);

-- Tabulka pro návštěvy pacienta
create table navstevy (
   cislo_navstevy    number
      generated by default as identity
   primary key,
   datum_a_cas       timestamp not null,
   typ_navstevy      varchar2(20) not null,
   cislo_pacienta    number not null,
   typ_prohlidky     number, -- Pokud je návštěva součástí prohlídky
   constraint chk_typ_navstevy 
      check ( typ_navstevy in ( 'planovana', 'akutni' ) ),
   constraint fk_navstevy_pacienti foreign key ( cislo_pacienta )
      references pacienti ( cislo_pacienta )
         on delete cascade,
   constraint fk_navstevy_prohlidky foreign key ( typ_prohlidky )
      references pravidelne_prohlidky ( typ_prohlidky )
         on delete set null
);

-- Spojovací tabulka N:M pro výkony provedené během návštěvy
create table navsteva_vykon (
   cislo_navstevy    number not null,
   typ_vykonu        number not null,
   primary key ( cislo_navstevy, typ_vykonu ),
   constraint fk_navvyk_navstevy foreign key ( cislo_navstevy )
      references navstevy ( cislo_navstevy )
         on delete cascade,
   constraint fk_navvyk_vykony foreign key ( typ_vykonu )
      references vykony ( typ_vykonu )
         on delete cascade
);

-- Tabulka pro očkování (vazba na pacienta, návštěvu a typ)
create table ockovani (
   id_ockovani       number
      generated by default as identity
   primary key,
   datum_ockovani    date not null,
   popis             varchar2(500),
   cislo_pacienta    number not null,
   cislo_navstevy    number not null,
   typ_ockovani_id   number not null,
   constraint fk_ockovani_pacienti foreign key ( cislo_pacienta )
      references pacienti ( cislo_pacienta )
         on delete cascade,
   constraint fk_ockovani_navstevy foreign key ( cislo_navstevy )
      references navstevy ( cislo_navstevy )
         on delete cascade,
   constraint fk_ockovani_typy foreign key ( typ_ockovani_id )
      references typy_ockovani ( typ_ockovani_id )
         on delete cascade
);

-- Tabulka pro lékařské předpisy (recepty)
create table predpisy (
   cislo_predpisu    number
      generated by default as identity
   primary key,
   datum_vystaveni   date not null,
   davkovani         varchar2(100),
   cislo_navstevy    number not null,
   cislo_leku        number not null,
   constraint fk_predpisy_navstevy foreign key ( cislo_navstevy )
      references navstevy ( cislo_navstevy )
         on delete cascade,
   constraint fk_predpisy_leky foreign key ( cislo_leku )
      references leky ( cislo_leku )
         on delete cascade
);

-- Tabulka pro externí vyšetření
create table externi_vysetreni (
   id_ex_vysetreni   number
      generated by default as identity
   primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500),
   pracoviste        varchar2(200) not null,
   cislo_navstevy    number not null,
   constraint fk_externi_navstevy foreign key ( cislo_navstevy )
      references navstevy ( cislo_navstevy )
         on delete cascade
);

