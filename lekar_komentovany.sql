-- ============================================================================
-- 1. MAZÁNÍ EXISTUJÍCÍCH TABULEK (DROP TABLES)
-- Předtím než vytvoříme nové tabulky, musíme smazat ty staré, aby skript nehlásil chyby.
-- Kvůli cizím klíčům (propojení tabulek) je mažeme v určitém pořadí.
-- ============================================================================

-- Blok 'begin ... end' v Oracle umožňuje spustit kód, který ignoruje chyby.
-- 'execute immediate' provede příkaz k smazání tabulky.
-- 'CASCADE CONSTRAINTS' zajistí, že se smažou i vazby na jiné tabulky.
-- 'exception when others then null' říká: "Pokud tabulka neexistuje, nic nedělej a pokračuj."

begin execute immediate 'DROP TABLE externi_vysetreni CASCADE CONSTRAINTS'; exception when others then null; end;
/
begin execute immediate 'DROP TABLE predpisy CASCADE CONSTRAINTS'; exception when others then null; end;
/
