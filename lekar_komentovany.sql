begin execute immediate 'DROP TABLE navstevy CASCADE CONSTRAINTS'; exception when others then null; end;
/
begin execute immediate 'DROP TABLE pacienti_registrovani CASCADE CONSTRAINTS'; exception when others then null; end;
/
begin execute immediate 'DROP TABLE pacienti CASCADE CONSTRAINTS'; exception when others then null; end;
/
begin execute immediate 'DROP TABLE pojistovny CASCADE CONSTRAINTS'; exception when others then null; end;
/
begin execute immediate 'DROP TABLE leky CASCADE CONSTRAINTS'; exception when others then null; end;
/
begin execute immediate 'DROP TABLE typy_ockovani CASCADE CONSTRAINTS'; exception when others then null; end;
/
begin execute immediate 'DROP TABLE pravidelne_prohlidky CASCADE CONSTRAINTS'; exception when others then null; end;
/
begin execute immediate 'DROP TABLE vykony CASCADE CONSTRAINTS'; exception when others then null; end;
/

-- ============================================================================
-- 2. VYTVÁŘENÍ TABULEK (CREATE TABLES)
-- Zde definujeme strukturu databáze - názvy sloupců, jejich typy a pravidla (omezení).
-- ============================================================================

-- Číselník pojišťoven
create table pojistovny (
   cislo_pojistovny  number(3) primary key, -- 3-místné číslo, slouží jako unikátní identifikátor (Primární klíč)
   nazev             varchar2(100) not null, -- Text do 100 znaků, nesmí být prázdný (NOT NULL)
   adresa            varchar2(200)           -- Text do 200 znaků
);

-- Hlavní tabulka pacientů
create table pacienti (
   cislo_pacienta    number
      generated by default as identity       -- Databáze sama generuje unikátní čísla (1, 2, 3...)
   primary key,                              -- Hlavní klíč tabulky
   jmeno             varchar2(50) not null,   -- Křestní jméno
   prijmeni          varchar2(50) not null,   -- Příjmení
   rodne_cislo       varchar2(11) not null,  -- Rodné číslo jako text
   telefon           varchar2(20),           -- Telefonní číslo
   datum_narozeni    date,                   -- Datumový typ
   adresa            varchar2(200),          -- Adresa bydliště
   cislo_pojistovny  number(3) not null,     -- Odkaz na pojišťovnu (bude z něj Cizí klíč)
   
   -- Kontrola formátu rodného čísla pomocí regulárního výrazu (Regex)
   constraint chk_rodne_cislo 
      check ( regexp_like ( rodne_cislo, '^[0-9]{6}/?[0-9]{3,4}$' ) ),
   
   -- Definice cizího klíče (Foreign Key) - propojení s tabulkou pojistovny
   constraint fk_pacienti_pojistovny foreign key ( cislo_pojistovny )
      references pojistovny ( cislo_pojistovny )
);

-- Podtabulka pro registrované pacienty (Generalizace)
-- Obsahuje jen data navíc, která akutní pacienti nemají.
create table pacienti_registrovani (
   cislo_pacienta    number primary key,     -- Identifikátor shodný s tabulkou 'pacienti'
   cislo_karty       number not null unique, -- Unikátní číslo lékařské karty
   
   -- Propojení podtabulky s hlavní tabulkou pacientů
   constraint fk_registrovani_pacienti foreign key ( cislo_pacienta )
      references pacienti ( cislo_pacienta )
         on delete cascade                  -- Pokud smažeme pacienta, smaže se i jeho registrace
);

-- Katalog lékařských výkonů
create table vykony (
   typ_vykonu        number generated by default as identity primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500)
);

-- Katalog typů očkování
create table typy_ockovani (
   typ_ockovani_id   number generated by default as identity primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500),
   doba_ucinnosti    number                  -- Počet měsíců platnosti očkování
);

-- Katalog typů pravidelných prohlídek
create table pravidelne_prohlidky (
   typ_prohlidky     number generated by default as identity primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500),
   doba_frekvence    number                  -- Jak často má pacient chodit (v měsících)
);

-- Katalog léků
create table leky (
   cislo_leku        number generated by default as identity primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500)
);

-- Evidence návštěv v ordinaci
create table navstevy (
   cislo_navstevy    number generated by default as identity primary key,
   datum_a_cas       timestamp not null,     -- Datum a přesný čas (vteřiny)
   typ_navstevy      varchar2(20) not null,  -- Např. 'akutni' nebo 'planovana'
   cislo_pacienta    number not null,        -- Kdo přišel (Cizí klíč)
   typ_prohlidky     number,                 -- O jakou prohlídku šlo (pokud o nějakou šlo)
   
   -- Omezení: typ návštěvy může být jen jeden z těchto dvou
   constraint chk_typ_navstevy 
      check ( typ_navstevy in ( 'planovana', 'akutni' ) ),
      
   -- Vazba na pacienta
   constraint fk_navstevy_pacienti foreign key ( cislo_pacienta )
      references pacienti ( cislo_pacienta ) on delete cascade,
      
   -- Vazba na číselník prohlídek
   constraint fk_navstevy_prohlidky foreign key ( typ_prohlidky )
      references pravidelne_prohlidky ( typ_prohlidky ) on delete set null
);

-- M:N vazba (Návštěva vs Výkon)
-- Během jedné návštěvy může být provedeno více výkonů.
-- Jeden typ výkonu může být proveden při mnoha návštěvách.
create table navsteva_vykon (
   cislo_navstevy    number not null,
   typ_vykonu        number not null,
   primary key ( cislo_navstevy, typ_vykonu ), -- Složený primární klíč
   
   constraint fk_navvyk_navstevy foreign key ( cislo_navstevy )
      references navstevy ( cislo_navstevy ) on delete cascade,
   constraint fk_navvyk_vykony foreign key ( typ_vykonu )
      references vykony ( typ_vykonu ) on delete cascade
);

-- Evidence konkrétních očkování
create table ockovani (
   id_ockovani       number generated by default as identity primary key,
   datum_ockovani    date not null,
   popis             varchar2(500),
   cislo_pacienta    number not null,
   cislo_navstevy    number not null,
   typ_ockovani_id   number not null,
   
   constraint fk_ockovani_pacienti foreign key ( cislo_pacienta ) references pacienti(cislo_pacienta) on delete cascade,
   constraint fk_ockovani_navstevy foreign key ( cislo_navstevy ) references navstevy(cislo_navstevy) on delete cascade,
   constraint fk_ockovani_typy foreign key ( typ_ockovani_id ) references typy_ockovani(typ_ockovani_id) on delete cascade
);

-- Evidence lékařských předpisů (receptů)
create table predpisy (
   cislo_predpisu    number generated by default as identity primary key,
   datum_vystaveni   date not null,
   davkovani         varchar2(100),
   cislo_navstevy    number not null,
   cislo_leku        number not null,
   
   constraint fk_predpisy_navstevy foreign key ( cislo_navstevy ) references navstevy(cislo_navstevy) on delete cascade,
   constraint fk_predpisy_leky foreign key ( cislo_leku ) references leky(cislo_leku) on delete cascade
);

-- Externí vyšetření (referraly)
create table externi_vysetreni (
   id_ex_vysetreni   number generated by default as identity primary key,
   nazev             varchar2(100) not null,
   popis             varchar2(500),
   pracoviste        varchar2(200) not null, -- Kam má pacient jít (název nemocnice)
   cislo_navstevy    number not null,
   
   constraint fk_externi_navstevy foreign key ( cislo_navstevy ) references navstevy(cislo_navstevy) on delete cascade
);

